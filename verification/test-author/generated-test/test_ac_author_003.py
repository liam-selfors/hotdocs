import json
import re

import pytest

import test_author


CANONICAL_MODEL = "canonical-mock-model"


def field(value, name):
    return value[name] if isinstance(value, dict) else getattr(value, name)


def _bundle():
    return {
        "component_id": "comp-widget-maker",
        "criterion_id": "AC-WIDGET-MAKER-001",
        "covers": "R-WIDGET-MAKER-001",
        "criterion_text": "Given a widget\nWhen it is made\nThen it exists",
        "requirement_text": "R-WIDGET-MAKER-001 - make_widget MUST return a widget.",
        "interface": "make_widget(name: str) -> dict",
        "glossary": "",
        "dependency_interfaces": {},
    }


def _write_probe_stand_in(repo_root, log_path):
    probe_dir = repo_root / "gen" / "test-probe"
    probe_dir.mkdir(parents=True, exist_ok=True)
    source = (
        "from dataclasses import dataclass, field\n"
        "\n"
        "GATE_VERSION = 'test-probe@1.4.0'\n"
        "\n"
        "\n"
        "@dataclass\n"
        "class ProbeReport:\n"
        "    ok: bool\n"
        "    findings: list = field(default_factory=list)\n"
        "    tests_run: int = 0\n"
        "    tests_reached: int = 0\n"
        "\n"
        "    def to_dict(self):\n"
        "        return {\n"
        "            'ok': self.ok,\n"
        "            'findings': list(self.findings),\n"
        "            'tests_run': self.tests_run,\n"
        "            'tests_reached': self.tests_reached,\n"
        "        }\n"
        "\n"
        "\n"
        "def probe(test_source, criterion_bundle, module_name, *, timeout=60.0,\n"
        "          interpreter=None, assets=None):\n"
        "    with open(" + repr(str(log_path)) + ", 'a', encoding='utf-8') as fh:\n"
        "        fh.write('probe\\n')\n"
        "    return ProbeReport(ok=True, findings=[], tests_run=1, tests_reached=1)\n"
    )
    (probe_dir / "test_probe.py").write_text(source, encoding="utf-8")


def _plant_generator_provenance(repo_root, model_a):
    """The component's current code was generated by model A."""
    gen_dir = repo_root / "gen" / "widget-maker"
    gen_dir.mkdir(parents=True, exist_ok=True)
    (gen_dir / "widget_maker.py").write_text(
        "# generated by " + model_a + "\n"
        "def make_widget(name):\n"
        "    return {'name': name}\n",
        encoding="utf-8",
    )
    manifest = {
        "component_id": "comp-widget-maker",
        "model": model_a,
        "generator": {"model": model_a, "seed": 0},
        "files": ["widget_maker.py"],
    }
    (gen_dir / ".provenance.json").write_text(json.dumps(manifest), encoding="utf-8")


GOOD_TEST = (
    "import widget_maker\n"
    "\n"
    "\n"
    "def test_make_widget():\n"
    "    assert widget_maker.make_widget('a') is not None\n"
)


@pytest.mark.parametrize(
    "model_a",
    [
        "anthropic:claude-opus-5-5",
        "ollama:llama3.1:8b",
        "gpt-6-astra",
        "some-other-generator-model",
    ],
)
def test_author_test_calls_model_with_canonical_model_regardless_of_generator_model(
    tmp_path, monkeypatch, model_a
):
    repo_root = tmp_path / ("repo_" + re.sub(r"[^a-z0-9]", "_", model_a.lower()))
    repo_root.mkdir()
    monkeypatch.chdir(repo_root)

    probe_log = tmp_path / ("probe_calls_" + repo_root.name + ".log")
    _write_probe_stand_in(repo_root, probe_log)
    _plant_generator_provenance(repo_root, model_a)

    seen_models = []

    def backend(prompt, model, **params):
        seen_models.append(model)
        nonce = re.findall(r"-----BEGIN FILE ([0-9a-f]{32})-----", prompt)[-1]
        text = (
            "-----BEGIN FILE " + nonce + "-----\n"
            + GOOD_TEST
            + "\n-----END FILE " + nonce + "-----"
        )
        return {
            "text": text,
            "model": model,
            "backend": "mock",
            "model_call_error": None,
        }

    result = test_author.author_test(
        _bundle(), CANONICAL_MODEL, 0, repo_root=repo_root, llm_backend=backend
    )

    # The model was called, and every call used the canonical model alone.
    assert seen_models, "the model backend was never called"
    assert all(m == CANONICAL_MODEL for m in seen_models), seen_models
    assert model_a not in seen_models

    assert field(result, "model_call_error") is None
    assert field(result, "model") == CANONICAL_MODEL