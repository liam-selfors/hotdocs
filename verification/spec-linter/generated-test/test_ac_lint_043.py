def write_corpus(repo_root, changes=None):
    files = {**CLEAN_CORPUS, **(changes or {})}
    for rel, text in files.items():
        if text is not None:
            path = repo_root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")


def field(value, name):
    return value[name] if isinstance(value, dict) else getattr(value, name)


def test_ac_lint_043_component_dir_without_component_md(tmp_path):
    repo_root = tmp_path
    changes = {
        "specs/components/ghost/requirements/R-GHOST-001.md": (
            "# R-GHOST-001\n\n**R-GHOST-001** — x.\n"
        ),
    }
    write_corpus(repo_root, changes)

    report = spec_linter.lint(None, repo_root)

    findings = list(field(report, "findings"))
    assert len(findings) == 1, [
        (field(f, "rule_id"), field(f, "file"), field(f, "message"))
        for f in findings
    ]
    finding = findings[0]
    assert field(finding, "rule_id") == "R-LINT-037"
    assert field(finding, "severity") == "fail"
    assert field(finding, "file") == "specs/components/ghost/"
    assert field(finding, "line") == 1
    assert field(finding, "message") == "specs/components/ghost/ has no component.md"